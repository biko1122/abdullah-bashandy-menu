/**
 * ==========================================================================
 *  إعدادات الطلب — عدّل من هنا فقط
 * --------------------------------------------------------------------------
 *  رسوم التوصيل، الحد الأدنى للأوردر، ومواعيد التوصيل.
 *
 *  ⚠️ مهم تفهم دي: الأرقام اللي هنا **للعرض بس**.
 *     السيرفر هو اللي بيحسب الحساب النهائي من قاعدة البيانات، ومبيثقش
 *     في أي رقم جاي من المتصفح. لو غيّرت الرقم هنا من غير ما تغيّره في
 *     الباكند، السيرفر هيرفض ويحسب بالرقم بتاعه.
 *
 *     الرقم في الباكند موجود في ملف .env باسم DELIVERY_FEE
 * ==========================================================================
 */

/** أنواع الطلب اللي الزبون بيختار منها قبل ما يطلب. */
export const ORDER_TYPES = [
  {
    id: 'DELIVERY',
    name: 'توصيل',
    note: 'نوصّلك لحد البيت',
    /* التوصيل محتاج عنوان */
    requiresAddress: true,
  },
  {
    id: 'PICKUP',
    name: 'استلام من الفرع',
    note: 'تيجي تاخده بنفسك',
    requiresAddress: false,
  },
]

/**
 * رسوم التوصيل بالجنيه.
 * 0 = المطعم بيحدد الرسوم بنفسه وقت ما يكلّم الزبون يأكد الطلب —
 * والموقع بيكتب "بيحددها المطعم" بدل رقم. لو حبيت تثبّت رقم بعدين،
 * حطه هنا **وفي bashandy-backend/.env (DELIVERY_FEE)** عشان يفضلوا متطابقين.
 */
export const DELIVERY_FEE = 0

/** أقل قيمة أوردر مقبولة (من غير رسوم التوصيل). 0 = مفيش حد أدنى. */
export const MIN_ORDER_TOTAL = 0

/** بيرجّع رسوم التوصيل حسب نوع الطلب. */
export const deliveryFeeFor = (orderType) =>
  orderType === 'DELIVERY' ? DELIVERY_FEE : 0

/** الحساب النهائي — نفس المعادلة اللي في السيرفر بالظبط. */
export const calculateTotals = (subtotal, orderType) => {
  const fee = deliveryFeeFor(orderType)
  return {
    subtotal,
    deliveryFee: fee,
    total: subtotal + fee,
  }
}

export default { ORDER_TYPES, DELIVERY_FEE, MIN_ORDER_TOTAL, deliveryFeeFor, calculateTotals }
